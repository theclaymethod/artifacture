import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformWgsl } from '@vgpu/wgsl/loader-vite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCENES_DIR = path.join(ROOT, 'src', 'scenes');

async function buildDir(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  let count = 0;
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      count += await buildDir(full);
      continue;
    }
    if (!entry.isFile() || !entry.name.endsWith('.wgsl')) continue;
    const { readFile } = await import('node:fs/promises');
    const source = await readFile(full, 'utf8');
    const transformed = await transformWgsl({
      source,
      id: full,
      minify: { whitespace: true, identifiers: 'none' },
    });
    const outPath = `${full}.ts`;
    const banner = '// Generated by @artifacture/gpu scripts/build-shaders.mjs — do not edit manually.\n// @ts-nocheck\n';
    await writeFile(outPath, `${banner}${transformed.code}\n`, 'utf8');
    count += 1;
  }
  return count;
}

const built = await buildDir(SCENES_DIR);
console.log(`Compiled ${built} WGSL shader module(s) in ${SCENES_DIR}`);
