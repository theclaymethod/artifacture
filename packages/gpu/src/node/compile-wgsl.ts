import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { transformWgsl } from '@vgpu/wgsl/loader-vite';

export interface CompileWgslOptions {
  readonly minify?:
    | boolean
    | { readonly whitespace?: boolean; readonly identifiers?: 'none' | 'safe' };
}

export interface CompiledShaderResult {
  readonly entryPath: string;
  readonly outPath: string;
}

/**
 * Compile a `.wgsl` file (including `@vgpu/wgsl-std` and relative imports)
 * into a zero-parser `.wgsl.ts` ES module exporting a prepared frozen `ShaderSource`.
 *
 * This lets stock `open-slide` workspaces (whose Vite config sets `configFile: false`)
 * import WGSL shaders cleanly with full build-time reflection and zero runtime WGSL parser.
 */
export async function compileWgslFile(
  entryPath: string,
  options: CompileWgslOptions = {},
): Promise<CompiledShaderResult> {
  const abs = path.resolve(entryPath);
  const source = await readFile(abs, 'utf8');
  const transformed = await transformWgsl({
    source,
    id: abs,
    minify: options.minify ?? { whitespace: true, identifiers: 'none' },
  });
  const outPath = `${abs}.ts`;
  await mkdir(path.dirname(outPath), { recursive: true });
  const banner =
    '// Generated by @artifacture/gpu compileWgslFile — do not edit manually.\n// @ts-nocheck\n';
  await writeFile(outPath, `${banner}${transformed.code}\n`, 'utf8');
  return { entryPath: abs, outPath };
}

async function collectWgsl(dir: string): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true });
  const files: string[] = [];
  for (const entry of entries) {
    if (entry.name === 'node_modules' || entry.name === 'dist' || entry.name === '.git') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectWgsl(full)));
    } else if (entry.isFile() && entry.name.endsWith('.wgsl')) {
      files.push(full);
    }
  }
  return files;
}

export async function compileWgslDirectory(
  rootDir: string,
  options: CompileWgslOptions = {},
): Promise<CompiledShaderResult[]> {
  const files = await collectWgsl(path.resolve(rootDir));
  const results: CompiledShaderResult[] = [];
  for (const file of files) {
    results.push(await compileWgslFile(file, options));
  }
  return results;
}
