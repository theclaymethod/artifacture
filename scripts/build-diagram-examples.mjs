import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const assets = new URL('plugins/visual-explainer/vendor/diagram-design/skills/diagram-design/assets/', root);
const examples = {};
for (const name of (await readdir(assets)).sort()) {
  if (!/^example-.*\.html$/.test(name)) continue;
  const key = name.slice(8, -5);
  const html = await readFile(new URL(name, assets), 'utf8');
  const title = /<title>([^<]+)<\/title>/.exec(html)?.[1] ?? key.replaceAll('-', ' ');
  examples[key] = { title, html };
}
const destination = new URL('visual-explainer-mdx/diagram-design-examples.ts', root);
const source = `// Generated by scripts/build-diagram-examples.mjs. Original HTML is preserved unchanged.\n// Cathryn Lavery, MIT; see DIAGRAM-DESIGN-LICENSE and the vendored provenance manifest.\nexport const diagramDesignExamples = ${JSON.stringify(examples, null, 2)} as const;\n\nexport type DiagramDesignExample = keyof typeof diagramDesignExamples;\n`;
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== source) throw new Error('Run npm run build:diagram-examples to refresh the original diagrams.');
} else await writeFile(destination, source);
console.log(`${Object.keys(examples).length} original diagrams: ${fileURLToPath(destination)}`);
