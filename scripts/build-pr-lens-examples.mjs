#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseGraphDoc } from '@coldtea/pr-lens-schema';
import { renderAll, RENDERER_VERSION } from '@coldtea/pr-lens-renderer';

const root = path.resolve(import.meta.dirname, '..');
const examples = {};
for (const name of ['minimal', 'postmark-refactor', 'broadcast-baseline', 'payload']) {
  const source = await readFile(path.join(root, `plugins/visual-explainer/vendor/pr-lens/packages/schema/examples/${name}.graph.json`), 'utf8');
  const doc = parseGraphDoc(JSON.parse(source));
  const { assets } = renderAll(doc);
  for (const asset of assets) {
    const key = `${name}/${asset.lens}/${asset.view ?? 'root'}/${asset.theme}`;
    examples[key] = { title: doc.title, lens: asset.lens, theme: asset.theme, svg: asset.svg, width: asset.width, height: asset.height };
  }
}
const output = path.join(root, 'visual-explainer-mdx/pr-lens-examples.ts');
const content = `// Generated by the original PR Lens renderer ${RENDERER_VERSION}; do not edit.\nexport const prLensExamples = ${JSON.stringify(examples)} as const;\nexport type PrLensExample = keyof typeof prLensExamples;\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== content) throw new Error('Original PR Lens examples are stale. Run npm run build:pr-lens-examples.');
} else await writeFile(output, content);
console.log(`${Object.keys(examples).length} original PR Lens SVGs, renderer ${RENDERER_VERSION}.`);
